// Generates a ready-to-build Fabric mod project (zip) and optionally creates a
// Modrinth draft project using the *user's own* token, so it lives under their name.
import archiver from "archiver";

const slugify = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "") || "my_mod";

export function modFiles({ name, author, description, mcVersion = "1.21.1", license = "MIT", items = [] }) {
  const id = slugify(name);
  const cls = id.split("_").map(p => p[0].toUpperCase() + p.slice(1)).join("");
  const pkg = `com.${slugify(author)}.${id}`;
  const itemRegs = items.map(i => {
    const iid = slugify(i);
    return `    public static final Item ${iid.toUpperCase()} = Registry.register(Registries.ITEM,\n        Identifier.of(MOD_ID, "${iid}"), new Item(new Item.Settings()));`;
  }).join("\n");
  const lang = Object.fromEntries(items.map(i => [`item.${id}.${slugify(i)}`, i]));

  return {
    [`src/main/java/${pkg.replace(/\./g, "/")}/${cls}.java`]:
`package ${pkg};

import net.fabricmc.api.ModInitializer;
import net.minecraft.item.Item;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.util.Identifier;

public class ${cls} implements ModInitializer {
    public static final String MOD_ID = "${id}";
${itemRegs}

    @Override
    public void onInitialize() {}
}
`,
    "src/main/resources/fabric.mod.json": JSON.stringify({
      schemaVersion: 1, id, version: "1.0.0", name, description,
      authors: [author], license, environment: "*",
      entrypoints: { main: [`${pkg}.${cls}`] },
      depends: { fabricloader: ">=0.16.0", minecraft: `~${mcVersion}`, "fabric-api": "*" },
    }, null, 2),
    [`src/main/resources/assets/${id}/lang/en_us.json`]: JSON.stringify(lang, null, 2),
    "gradle.properties":
`minecraft_version=${mcVersion}
loader_version=0.16.5
mod_version=1.0.0
maven_group=${pkg}
archives_base_name=${id}
`,
    "README.md": `# ${name}\n\n${description}\n\nGenerated by ForgeCenter. Copy these files into the Fabric example mod template (https://github.com/FabricMC/fabric-example-mod) and run \`./gradlew build\`.\n\nLicense: ${license}\n`,
    "LICENSE": license === "MIT"
      ? `MIT License\n\nCopyright (c) ${new Date().getFullYear()} ${author}\n\nPermission is hereby granted, free of charge, to any person obtaining a copy\nof this software and associated documentation files (the "Software"), to deal\nin the Software without restriction, including without limitation the rights\nto use, copy, modify, merge, publish, distribute, sublicense, and/or sell\ncopies of the Software, subject to the above copyright notice being included.\n\nTHE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND.\n`
      : `${license}\n`,
  };
}

export function streamZip(files, res, filename, ext = "zip") {
  res.setHeader("Content-Type", ext === "mrpack" ? "application/x-modrinth-modpack+zip" : "application/zip");
  res.setHeader("Content-Disposition", `attachment; filename="${filename}.${ext}"`);
  const zip = archiver("zip");
  zip.pipe(res);
  for (const [path, content] of Object.entries(files)) zip.append(content, { name: path });
  zip.finalize();
}

export async function createModrinthProject({ token, name, description, license }) {
  const slug = slugify(name).replace(/_/g, "-");
  const data = {
    slug, title: name, description: description.slice(0, 256),
    body: `# ${name}\n\n${description}\n\nMade with ForgeCenter.`,
    categories: ["utility"], client_side: "required", server_side: "optional",
    project_type: "mod", license_id: license, is_draft: true, initial_versions: [],
  };
  const form = new FormData();
  form.append("data", JSON.stringify(data));
  const r = await fetch("https://api.modrinth.com/v2/project", {
    method: "POST",
    headers: { Authorization: token, "User-Agent": "ForgeCenter/0.1" },
    body: form,
  });
  const body = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(body.description || `Modrinth error ${r.status}`);
  return { url: `https://modrinth.com/mod/${body.slug || slug}`, id: body.id };
}
